CREATE TABLE IF NOT EXISTS plenty_rate_limits (
 bucket CHAR(64) NOT NULL PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_start BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plenty_obras (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(190) NOT NULL,
 created_by BIGINT UNSIGNED NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_obra_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS plenty_responsaveis (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(190) NOT NULL,
 created_by BIGINT UNSIGNED NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_resp_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS plenty_visits (
 id VARCHAR(64) NOT NULL PRIMARY KEY,
 os VARCHAR(32) NOT NULL,
 obra VARCHAR(190) NOT NULL,
 data DATE NOT NULL,
 local VARCHAR(190) NOT NULL DEFAULT '',
 endereco VARCHAR(255) NOT NULL DEFAULT '',
 solicitante VARCHAR(190) NOT NULL DEFAULT '',
 tipo VARCHAR(80) NOT NULL,
 responsavel VARCHAR(190) NOT NULL,
 tecnico VARCHAR(190) NOT NULL DEFAULT '',
 objetivo MEDIUMTEXT NOT NULL,
 situacao MEDIUMTEXT NOT NULL,
 elemento VARCHAR(255) NOT NULL DEFAULT '',
 anomalia VARCHAR(255) NOT NULL DEFAULT '',
 causa VARCHAR(255) NOT NULL DEFAULT '',
 origem VARCHAR(40) NOT NULL DEFAULT 'A apurar',
 risco VARCHAR(20) NOT NULL DEFAULT 'Médio',
 prioridade VARCHAR(20) NOT NULL DEFAULT 'Média',
 diagnostico MEDIUMTEXT NOT NULL,
 acao MEDIUMTEXT NOT NULL,
 prazo DATE NULL,
 status VARCHAR(40) NOT NULL DEFAULT 'Aberta',
 foto MEDIUMTEXT NULL,
 created_by BIGINT UNSIGNED NULL,
 updated_by BIGINT UNSIGNED NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_visits_data (data),
 KEY idx_visits_status (status),
 KEY idx_visits_obra (obra)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS plenty_audit (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NULL,
 action VARCHAR(64) NOT NULL,
 detail VARCHAR(500) NOT NULL DEFAULT '',
 ip VARCHAR(64) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_audit_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
